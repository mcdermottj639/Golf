const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const feed = JSON.parse(fs.readFileSync(path.join(__dirname, '../coach-feed.json'), 'utf8'));

const ids = feed.entries.filter(e => String(e.id).includes('20260922-range')).map(e => e.id);
assert.deepEqual(ids, ['bay-20260922-range-8i-5i']);
const bay = feed.entries.find(e => e.id === 'bay-20260922-range-8i-5i');
assert.equal(bay.bay.date, '2026-09-22');
assert.match(bay.bay.setup, /one session/i);
assert.doesNotMatch(bay.bay.finding, /morning|afternoon/i);
const groups = bay.bay.detail.rangeShots;
assert.deepEqual(groups.map(g => g.club), ['8-iron', '5-iron']);
assert.equal(groups[0].shots.length, 4);
assert.equal(groups[0].shots.filter(s => s.mishit).length, 1);
assert.equal(groups[1].shots.length, 26);
assert.equal(groups[1].shots.filter(s => s.src === 'table-9').length, 9);
assert.equal(groups[1].shots.filter(s => s.src === 'table-17').length, 17);
const five = bay.bay.detail.clubs.find(c => c.club === '5-iron');
assert.equal(five.n, 26);
assert.equal(five.carry, 141);
assert.equal(five.dynLoft, 22.1);
assert.equal(five.path, -3.2);
assert.equal(five.smash, 1.33);
const eight = bay.bay.detail.clubs.find(c => c.club === '8-iron');
assert.equal(eight.n, 3);
assert.equal(eight.carry, 102.3);
console.log('PASS: Sep 22 range is one session, 8-iron plus both 5-iron tables.');
