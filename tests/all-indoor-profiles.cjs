for(const p of ['lessons.js','courses-db.js','course-cards.js'])vm.runInContext(fs.readFileSync(path.join(root,p),'utf8'),ctx);
let app=fs.readFileSync(path.join(root,'app.js'),'utf8');
app=app.slice(0,app.indexOf('// ---------- Boot ----------'))+'\nrerender=()=>{};toast=()=>{};load();window.T={applyFeed,roundReviewBays,theNumbers,get:()=>S};})();';
vm.runInContext(app,ctx);
const T=ctx.window.T;
T.applyFeed(read('coach-feed.json'));
