T.applyFeed(read('corrections-20260922.json'));
const all=T.get().rounds.filter(r=>r.sim&&r.review);
assert.equal(all.length,4);
const baselines=T.roundReviewBays();
const haz=all.find(r=>r.course==='Hazeltine National');
const oldCount=haz.review.shots.length;
assert.equal(haz.review.profileMode,'selected-label');
assert.equal(haz.review.noBay,false);
const hp=R.profiles(haz,baselines);
assert.equal(hp.length,7);
assert.equal(hp.find(p=>p.club==='3-wood').carryN,7);
assert.equal(hp.find(p=>p.club==='3-wood').distanceN,17);
assert.equal(hp.find(p=>p.club==='3-wood').bay.carry,188.4);
assert.equal(hp.find(p=>p.club==='7-iron').bay.carry,130.5);
assert.equal(hp.find(p=>p.club==='2-iron').bay,undefined,'no matching source for 2-iron');
assert.ok(hp.every(p=>p.full.every(s=>s.actualClub===null)),'selected labels never assert actual club');
const hh=R.render(haz,{bays:baselines,rounds:all});
assert.match(hh,/Club selected/);
assert.match(hh,/Observed shots/);
assert.match(hh,/244 yd total/);
assert.match(hh,/205\.3/);
assert.match(hh,/selected on the TrackMan screen/);
assert.doesNotMatch(hh,/Bay comparison is off/);
assert.doesNotMatch(hh,/Spyglass Hole 1/);
assert.equal(haz.review.shots.length,oldCount);
const spy=all.find(r=>r.course==='Spyglass Hill');
assert.ok(R.profiles(spy,baselines).every(p=>p.bay));
assert.equal(R.profiles(spy,baselines).find(p=>p.club==='3-wood').n,14);
const bally=all.find(r=>r.course==='Ballybunion');
assert.equal(R.profiles(bally,baselines).find(p=>p.club==='mini-driver').bay,undefined,'historical Mini must not match current 3-wood');
const virtual=all.find(r=>r.course==='TrackMan Virtual · front nine');
assert.equal(virtual.review.distanceMeaning,'carry-only');
assert.ok(R.profiles(virtual,baselines).every(p=>p.bay===undefined && p.distance===null));
assert.equal(haz.score,80);
const numbers=T.theNumbers();
assert.match(numbers,/On-course · 6 logged/);
assert.match(numbers,/SIM <b>80<\/b> · 3/);
assert.equal(T.get().rounds.filter(r=>r.sim).length,4,'nine-hole simulator round is still in Days');
console.log('PASS four indoor cards: Hazeltine measured label-only samples and explicit range links, Spyglass confirmed clubs, Ballybunion Mini isolation, virtual carry-only.');
